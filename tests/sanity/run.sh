#!/usr/bin/env bash
set -Eeuo pipefail

script_path="$(readlink -f "${BASH_SOURCE[0]}")"
sanity_dir="$(cd "$(dirname "$script_path")" && pwd)"
driver_root="$(cd "$sanity_dir/../.." && pwd)"

if [[ "${1:-}" == -h || "${1:-}" == --help ]]; then
  echo "Usage: bash tests/sanity/run.sh <local|cloud> [--allow-live]"
  echo "       local runs the complete NFS csi-sanity suite with mock coordination"
  exit 0
fi

run_full_mock_as_root() {
  local env_file="$1"
  local root_home="${HOME:-/root}"
  local task_home=""

  [[ "$EUID" == 0 ]] || { echo "Internal full-mock mode requires sudo" >&2; exit 2; }
  [[ -r "$env_file" ]] || { echo "Missing temporary test environment file" >&2; exit 2; }
  # This file is generated by this runner with mode 0600 and contains the API key.
  # shellcheck disable=SC1090
  source "$env_file"

  mkdir -p "$root_home/.cache/ngxstorage"
  task_home="$(mktemp -d "$root_home/.cache/ngxstorage/nfs-full-run.XXXXXX")"
  export HOME="$task_home"
  export TMPDIR="$HOME/.cache/ngxstorage"
  export GOCACHE="$TMPDIR/go-cache"
  export PATH="$(dirname "$NFS_GO_BIN"):/usr/local/bin:/usr/bin:/bin"
  export GOROOT="$NFS_GOROOT"
  export GOPATH="$NFS_GOPATH"
  export GOMODCACHE="$NFS_GOMODCACHE"
  mkdir -p "$TMPDIR" "$GOCACHE"

  local -a host_link_paths=() host_link_ids=() host_link_targets=()

  cleanup_root() {
    # Preserve pre-existing paths and links replaced by another process.
    local host_index
    for ((host_index=${#host_link_paths[@]}-1; host_index>=0; host_index--)); do
      local created_path="${host_link_paths[host_index]}"
      if [[ -L "$created_path" &&
            "$(readlink -- "$created_path")" == "${host_link_targets[host_index]}" &&
            "$(stat -c '%d:%i' -- "$created_path")" == "${host_link_ids[host_index]}" ]]; then
        rm -- "$created_path"
      fi
    done
    rm -f "$env_file"
    if [[ -n "$task_home" && -d "$task_home" ]]; then
      local remaining_mounts=""
      if command -v findmnt >/dev/null 2>&1; then
        remaining_mounts="$(findmnt -rn -o TARGET | awk -v prefix="$task_home/" 'index($0, prefix) == 1')"
      fi
      if [[ -n "$remaining_mounts" ]]; then
        echo "Keeping temporary home because test mounts remain beneath it:" >&2
        printf '%s\n' "$remaining_mounts" >&2
      else
        rm -rf -- "$task_home"
      fi
    fi
  }
  trap cleanup_root EXIT

  # /host is normally the Kubernetes hostPath mount. Standalone tests
  # expose missing paths with symlinks, preserving existing host data/mounts.
  command -v flock >/dev/null || { echo "Local sanity requires flock" >&2; exit 2; }
  mkdir -p /run/lock
  exec 9>/run/lock/ngxstorage-csi-local-host.lock
  echo "Waiting for the local CSI host-root lock..."
  flock -x 9
  add_host_link() {
    local link_path="$1" link_target="$2"
    if [[ ! -e "$link_path" && ! -L "$link_path" ]]; then
      ln -sT -- "$link_target" "$link_path"
      host_link_paths+=("$link_path")
      host_link_ids+=("$(stat -c '%d:%i' -- "$link_path")")
      host_link_targets+=("$link_target")
      printf 'Created %s -> %s for local sanity.\n' "$link_path" "$link_target"
    fi
  }
  add_host_link /host /
  [[ -d /host ]] || { echo "Existing /host is not a usable directory" >&2; exit 2; }
  add_host_link /host/etc /etc
  add_host_link /host/sys /sys
  [[ -d /host/etc && -d /host/sys ]] || {
    echo "Existing /host/etc or /host/sys is not a usable directory" >&2
    exit 2
  }


  cd "$driver_root"
  local log_dir="$driver_root/tests/sanity/local/logs"
  local log_file="$log_dir/full-mock-$(date +%Y%m%d-%H%M%S)-$$.log"
  mkdir -p "$log_dir"
  printf 'Running full NFS csi-sanity suite as root; log: %s\n' "$log_file"

  set +e
  SANITY_MOCK_COORDINATION=1 SANITY_FULL=1 \
    bash "$driver_root/tests/run-all-tests.sh" sanity local --allow-live 2>&1 | tee "$log_file"
  local result="${PIPESTATUS[0]}"
  set -e
  printf '\nFull csi-sanity exit code: %s\nLog: %s\n' "$result" "$log_file"
  exit "$result"
}

if [[ "${1:-}" == --full-mock-as-root ]]; then
  [[ $# == 2 ]] || { echo "Internal invocation error" >&2; exit 2; }
  run_full_mock_as_root "$2"
fi

case "${1:-}" in
  local|cloud) mode="$1"; shift ;;
  *) echo "Usage: bash tests/sanity/run.sh <local|cloud> [--allow-live]" >&2; exit 2 ;;
esac

if [[ "$mode" == local ]]; then
  if [[ "${1:-}" == --allow-live ]]; then shift; fi
  [[ $# == 0 ]] || { echo "Usage: bash tests/sanity/run.sh local [--allow-live]" >&2; exit 2; }
  [[ "$EUID" != 0 ]] || { echo "Run this script as your normal user; it will request sudo itself." >&2; exit 2; }

  user_tmp="$HOME/.cache/ngxstorage"
  mkdir -p "$user_tmp"
  export TMPDIR="$user_tmp"
  export GOCACHE="${GOCACHE:-$TMPDIR/ngxstorage-csi-nfs-go-cache}"
  env_file="$(mktemp "$user_tmp/nfs-sanity-env.XXXXXX")"
  chmod 600 "$env_file"
  trap 'rm -f "$env_file"' EXIT

  # Single open runtime profile: credential, endpoints, pool and data IP all
  # come from tests/sanity/local/config.env and/or exported environment and
  # must describe the SAME storage runtime. Preflight fails on a missing or
  # partial profile; there are no silent defaults and no fallback channel
  # that scrapes documentation.
  # shellcheck source=tests/sanity/local/runtime-profile.sh
  source "$sanity_dir/local/runtime-profile.sh"
  sanity_profile_preflight "$sanity_dir/local/config.env"

  export NFS_GO_BIN="$(command -v go)"
  export NFS_GOROOT="$(go env GOROOT)"
  export NFS_GOPATH="$(go env GOPATH)"
  export NFS_GOMODCACHE="$(go env GOMODCACHE)"

  # Resolve the SHARED csi-sanity binary now, while HOME is the real home, so
  # the root full-mock run consumes a pinned path and never re-clones the fork
  # under its temporary HOME. csi_sanity_resolve prefers a verified prebuilt
  # when CSI_PREBUILT_DIR is set, else builds from the pinned fork commit.
  # shellcheck source=tests/sanity/cloud/prebuilt.sh
  source "$sanity_dir/cloud/prebuilt.sh"
  export CSI_SANITY_BIN="$driver_root/build/shared-sanity/csi-sanity"
  csi_sanity_resolve "$CSI_SANITY_BIN" || {
    echo "shared csi-sanity binary could not be resolved (fork @${CSI_TEST_FORK_SHA})" >&2
    exit 2
  }

  printf '%s\n' 'Checking NFS backend before requesting sudo...'
  NFS_LIVE_MOCK_PREFLIGHT=1 "$NFS_GO_BIN" test ./pkg/driver -run '^TestLocalSanityBackendPreflight$' -count=1
  python3 - "$env_file" <<'PY'
from pathlib import Path
import os
import shlex
import sys

keys = (
    "STORAGE_API_KEY", "STORAGE_IPS", "STORAGE_POOL_NAME", "STORAGE_DATA_IP",
    "NFS_GO_BIN", "NFS_GOROOT", "NFS_GOPATH", "NFS_GOMODCACHE",
    "CSI_SANITY_BIN",
)
values = {key: os.environ.get(key, "") for key in keys}
missing = [key for key, value in values.items() if not value]
if missing:
    raise SystemExit("Missing required settings: " + ", ".join(missing))
lines = [f"export {key}={shlex.quote(value)}\n" for key, value in values.items()]
# SANITY_SHARED_ARRAY is an OPT-IN flag, not a required setting: sudo strips
# the caller environment, so it only reaches the root full-mock run (and from
# there the csi-sanity binary) when carried through this file explicitly.
shared_array = os.environ.get("SANITY_SHARED_ARRAY", "")
if shared_array:
    lines.append(f"export SANITY_SHARED_ARRAY={shlex.quote(shared_array)}\n")
Path(sys.argv[1]).write_text("".join(lines))
PY
  sudo bash "$script_path" --full-mock-as-root "$env_file"
  exit $?
fi

exec bash "$sanity_dir/../run-all-tests.sh" sanity "$mode" "$@"
